class FeeCategory {
  final String id;
  final String accountId;
  final String name;
  final String? description;
  final bool isActive;
  final DateTime createdAt;
  final DateTime updatedAt;

  FeeCategory({
    required this.id,
    required this.accountId,
    required this.name,
    this.description,
    required this.isActive,
    required this.createdAt,
    required this.updatedAt,
  });

  factory FeeCategory.fromJson(Map<String, dynamic> json) {
    return FeeCategory(
      id: json['id'],
      accountId: json['account_id'],
      name: json['name'],
      description: json['description'],
      isActive: json['is_active'] ?? true,
      createdAt: DateTime.parse(json['created_at']),
      updatedAt: DateTime.parse(json['updated_at']),
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'account_id': accountId,
      'name': name,
      'description': description,
      'is_active': isActive,
      'created_at': createdAt.toIso8601String(),
      'updated_at': updatedAt.toIso8601String(),
    };
  }
}

class FeeStructure {
  final String id;
  final String accountId;
  final String categoryId;
  final String name;
  final double amount;
  final String studentClass;
  final DateTime? dueDate;
  final String? description;
  final bool isActive;
  final String planType;
  final double lateFine;
  final int graceDays;
  final double gstPercent;
  final bool autoGenerateDues;
  final DateTime createdAt;
  final DateTime updatedAt;
  final String? categoryName;

  FeeStructure({
    required this.id,
    required this.accountId,
    required this.categoryId,
    required this.name,
    required this.amount,
    required this.studentClass,
    this.dueDate,
    this.description,
    required this.isActive,
    required this.planType,
    required this.lateFine,
    required this.graceDays,
    required this.gstPercent,
    required this.autoGenerateDues,
    required this.createdAt,
    required this.updatedAt,
    this.categoryName,
  });

  factory FeeStructure.fromJson(Map<String, dynamic> json) {
    return FeeStructure(
      id: json['id'],
      accountId: json['account_id'],
      categoryId: json['category_id'],
      name: json['name'],
      amount: double.parse(json['amount'].toString()),
      studentClass: json['class'],
      dueDate: json['due_date'] != null ? DateTime.parse(json['due_date']) : null,
      description: json['description'],
      isActive: json['is_active'] ?? true,
      planType: json['plan_type'] ?? 'monthly',
      lateFine: double.parse((json['late_fine'] ?? 0).toString()),
      graceDays: json['grace_days'] ?? 0,
      gstPercent: double.parse((json['gst_percent'] ?? 0).toString()),
      autoGenerateDues: json['auto_generate_dues'] ?? true,
      createdAt: DateTime.parse(json['created_at']),
      updatedAt: DateTime.parse(json['updated_at']),
      categoryName: json['fee_categories']?['name'],
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'account_id': accountId,
      'category_id': categoryId,
      'name': name,
      'amount': amount,
      'class': studentClass,
      'due_date': dueDate?.toIso8601String(),
      'description': description,
      'is_active': isActive,
      'plan_type': planType,
      'late_fine': lateFine,
      'grace_days': graceDays,
      'gst_percent': gstPercent,
      'auto_generate_dues': autoGenerateDues,
      'created_at': createdAt.toIso8601String(),
      'updated_at': updatedAt.toIso8601String(),
    };
  }
}

