class Due {
  final String id;
  final String accountId;
  final String studentId;
  final String? feeStructureId;
  final String? batchId;
  final String periodName;
  final DateTime dueDate;
  final double amountAssigned;
  final double amountPaid;
  final double dueAmount;
  final double lateFineApplied;
  final String status;
  final String? notes;
  final DateTime createdAt;
  final DateTime updatedAt;
  final FeeStructure? feeStructure;

  Due({
    required this.id,
    required this.accountId,
    required this.studentId,
    this.feeStructureId,
    this.batchId,
    required this.periodName,
    required this.dueDate,
    required this.amountAssigned,
    required this.amountPaid,
    required this.dueAmount,
    required this.lateFineApplied,
    required this.status,
    this.notes,
    required this.createdAt,
    required this.updatedAt,
    this.feeStructure,
  });

  factory Due.fromJson(Map<String, dynamic> json) {
    return Due(
      id: json['id'],
      accountId: json['account_id'],
      studentId: json['student_id'],
      feeStructureId: json['fee_structure_id'],
      batchId: json['batch_id'],
      periodName: json['period_name'],
      dueDate: DateTime.parse(json['due_date']),
      amountAssigned: double.parse(json['amount_assigned'].toString()),
      amountPaid: double.parse((json['amount_paid'] ?? 0).toString()),
      dueAmount: double.parse((json['due_amount'] ?? 0).toString()),
      lateFineApplied: double.parse((json['late_fine_applied'] ?? 0).toString()),
      status: json['status'],
      notes: json['notes'],
      createdAt: DateTime.parse(json['created_at']),
      updatedAt: DateTime.parse(json['updated_at']),
      feeStructure: json['fee_structures'] != null 
        ? FeeStructure.fromJson(json['fee_structures']) 
        : null,
    );
  }

  String get formattedPeriodName {
    // Strips out "Batch <uuid> " from the periodName
    // UUIDs are 36 characters long. e.g., "Batch 9c7835e3-8ee6-4cfa-99fd-a3e8922a0389 Jun 2026" -> "Jun 2026"
    final regex = RegExp(r'^Batch [a-fA-F0-9\-]{36}\s+');
    final cleaned = periodName.replaceAll(regex, '');
    
    // Add "Fee" suffix if it's just a month/year or quarter to make it look better
    if (cleaned.contains(RegExp(r'^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\s+\d{4}$')) || 
        cleaned.contains(RegExp(r'^Q[1-4]\s+\d{4}$'))) {
      return '$cleaned Fee';
    }
    return cleaned;
  }
}

